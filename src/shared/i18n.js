  let current = FALLBACK;

  function normalize(raw) {
    const v = String(raw || '').toLowerCase().replace('_', '-');
    if (!v || v === 'auto') return null;
    if (v.indexOf('zh') === 0) return 'zh-CN';
    if (v.indexOf('ja') === 0) return 'ja';
    if (v.indexOf('fr') === 0) return 'fr';
    if (v.indexOf('de') === 0) return 'de';
    if (v.indexOf('es') === 0) return 'es';
    if (v.indexOf('en') === 0) return 'en';
    return FALLBACK;
  }

  /** 把 settings.locale（可能是 'auto'）解析成实际语言代码 */
  function resolve(pref) {
    const picked = normalize(pref);
    if (picked) return picked;
    try {
      if (chrome && chrome.i18n && chrome.i18n.getUILanguage) {
        const fromChrome = normalize(chrome.i18n.getUILanguage());
        if (fromChrome) return fromChrome;
      }
    } catch (err) {
      /* 忽略 */
    }
    return normalize(navigator.language) || FALLBACK;
  }

  function setLocale(pref) {
    current = resolve(pref);
    return current;
  }

  function getLocale() {
    return current;
  }

  function dict() {
    const d = MESSAGES[current];
    return d && Object.keys(d).length ? d : MESSAGES[FALLBACK];
  }

  function t(key, params) {
    const table = dict();
    let text = table[key];
    if (text === undefined) {
      text = MESSAGES[FALLBACK][key];
    }
    if (text === undefined) return key;
    if (params) {
      text = text.replace(/\{(\w+)\}/g, (match, name) =>
        params[name] === undefined ? match : String(params[name])
      );
    }
    return text;
  }

  /**
   * 替换 HTML 里带 data-i18n* 标记的文本。
   *   data-i18n             → textContent
   *   data-i18n-title       → title 属性
   *   data-i18n-placeholder → placeholder 属性
   */
  function applyI18n(rootEl) {
    const scope = rootEl || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    return scope;
  }

